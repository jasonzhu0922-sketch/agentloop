// Development-time schema introspection only. Native Redis never loads SQLite or SQL.
import { AppDatabase } from "../src/storage/database.ts";
import { readFile, writeFile } from "node:fs/promises";
const db = new AppDatabase(":memory:");
await db.ready();
try {
  const tables = await db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all();
  const metadata = {}, definitions = [];
  for (const { name, sql } of tables) {
    const columns = await db.prepare(`PRAGMA table_info("${name}")`).all();
    const foreignKeys = await db.prepare(`PRAGMA foreign_key_list("${name}")`).all();
    const indexes = await db.prepare(`PRAGMA index_list("${name}")`).all();
    const enums = Object.fromEntries([...sql.matchAll(/CHECK\s*\(\s*(\w+)\s+IN\s*\(([^)]*)\)\s*\)/gi)].map(([, column, values]) =>
      [column, values.split(",").map(value => { const text = value.trim(); return text.startsWith("'") ? text.slice(1, -1).replaceAll("''", "'") : Number(text); })]));
    if ((sql.match(/CHECK\s*\(/gi) ?? []).length !== Object.keys(enums).length) throw new Error(`Review new non-enum Runtime constraint in ${name}`);
    const defaults = Object.fromEntries(columns.map(column => {
      const value = column.dflt_value;
      return [column.name, value === null ? null : value.startsWith("'") ? value.slice(1, -1).replaceAll("''", "'") : JSON.parse(value)];
    }));
    const unique = [];
    for (const index of indexes.filter(index => index.unique)) unique.push((await db.prepare(`PRAGMA index_info("${index.name}")`).all()).map(column => column.name));
    metadata[name] = { key: columns.filter(column => column.pk).sort((a, b) => a.pk - b.pk).map(column => column.name), defaults,
      required: columns.filter(column => column.notnull || column.pk).map(column => column.name), unique, enums,
      foreignKeys: [...new Set(foreignKeys.map(fk => fk.id))].map(id => {
        const group = foreignKeys.filter(fk => fk.id === id).sort((a, b) => a.seq - b.seq);
        return { table: group[0].table, columns: group.map(fk => fk.from), references: group.map(fk => fk.to), onDelete: group[0].on_delete };
      }) };
    definitions.push(`  ${name}: {\n${columns.map(column => {
      const type = enums[column.name] ? enums[column.name].map(value => JSON.stringify(value)).join(" | ") : /INT|REAL|FLOAT|DOUBLE|NUMERIC/i.test(column.type) ? "number" : "string";
      return `    ${column.name}: ${type}${!column.notnull && !column.pk ? " | null" : ""};`;
    }).join("\n")}\n  };`);
  }
  const source = `// Generated by scripts/generate-runtime-record-schema.mjs; review schema changes with domain repositories.\nexport interface RuntimeRows {\n${definitions.join("\n")}\n}\nexport type RuntimeTable = keyof RuntimeRows;\nexport const runtimeRecordSchema = {\n${Object.entries(metadata).map(([name, value]) => `  ${name}: ${JSON.stringify(value)},`).join("\n")}\n} as const;\n`;
  const path = new URL("../src/storage/runtime-record-schema.ts", import.meta.url);
  if (process.argv.includes("--check")) { if (await readFile(path, "utf8") !== source) throw new Error("Runtime record schema is stale; regenerate and review it"); }
  else await writeFile(path, source);
} finally { await db.close(); }
