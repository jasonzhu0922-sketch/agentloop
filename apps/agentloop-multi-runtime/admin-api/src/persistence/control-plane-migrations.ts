async function withMigrationLock(database: SqlConnection, operation: () => Promise<void>): Promise<void> {
  if (database.dialect === "sqlite") return await database.transaction(operation);
  if (database.dialect === "postgres") {
    return await database.transaction(async () => {
      await database.prepare("SELECT pg_advisory_xact_lock(hashtext(?))").get("agentloop:control-plane:schema");
      await operation();
    });
  }
  const lock = await database.prepare("SELECT GET_LOCK(?, 60) AS acquired").get<{ acquired: number | string | null }>("agentloop:control-plane:schema");
  if (Number(lock?.acquired) !== 1) throw new ControlPlaneMigrationError("Timed out acquiring TiDB control-plane migration lock");
  try { await operation(); } finally { await database.prepare("SELECT RELEASE_LOCK(?)").get("agentloop:control-plane:schema"); }
}

function checksumFor(migration: ExecutableControlPlaneMigration): string {
  return createHash("sha256").update(`${migration.id}\n${migration.definition}`).digest("hex");
}
