import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { once } from "node:events";
import test from "node:test";
import { SqliteConnection } from "@zhujun/agentloop";
import { AccountServiceClient, IdentityService, RemoteIdentityService, IdentityError } from "@zhujun/agentloop-identity";
import { createAccountServer } from "../src/server.ts";

test("independent accounts persist one authority for Desktop and Router without Runtime or business state", async t => {
  const root = await mkdtemp(join(tmpdir(), "agentloop-cloud-accounts-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const path = join(root, "accounts.db"); let database = new SqliteConnection(path);
  let identity = new IdentityService(database); await identity.ready();
  let server = createAccountServer(identity); server.listen(0, "127.0.0.1"); await once(server, "listening");
  const address = server.address(); assert.ok(address && typeof address !== "string");
  const origin = `http://127.0.0.1:${address.port}`;
  t.after(async () => { await new Promise<void>(resolve => { server.close(() => resolve()); server.closeAllConnections(); }); await database.close(); });
  const desktop = new AccountServiceClient(origin), router = new RemoteIdentityService(origin);
  const email = "Owner@Example.test", password = "fixture-account-password-12";
  const registered = await desktop.authenticate("register", email, password);
  assert.equal(registered.principal.email, "owner@example.test");
  await assert.rejects(desktop.authenticate("register", email, password), error => error instanceof IdentityError && error.code === "email_registered");
  await assert.rejects(router.login(email, "wrong-password"), error => error instanceof IdentityError && error.code === "invalid_credentials");
  const fromRouter = await router.login(email, password);
  assert.deepEqual(fromRouter.principal, registered.principal);
  assert.deepEqual(await router.authenticate(`Bearer ${registered.token}`), registered.principal);
  const raw = await fetch(`${origin}/v1/auth/me`, { headers: { authorization: `Bearer ${registered.token}` } });
  assert.equal(raw.headers.get("access-control-allow-origin"), null);
  assert.equal((await fetch(`${origin}/v1/auth/register`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ email, password, ownerUserId: "forged" }) })).status, 400);
  assert.equal((await fetch(`${origin}/v1/auth/login`, { method: "POST", headers: { "content-type": "text/plain" }, body: "{}" })).status, 415);
  assert.equal((await fetch(`${origin}/v1/auth/login`, { method: "POST", headers: { "content-type": "application/json" }, body: "x".repeat(9000) })).status, 413);
  assert.equal((await fetch(`${origin}/v1/conversations`)).status, 404);
  const tables = await database.prepare("SELECT name FROM sqlite_master WHERE type='table'").all<{ name: string }>();
  assert.deepEqual(tables.map(row => row.name).sort(), ["mr_identity_memberships", "mr_identity_sessions", "mr_identity_tenants", "mr_identity_users"]);
  const user = await database.prepare("SELECT password_hash FROM mr_identity_users").get<{ password_hash: string }>();
  assert.match(user!.password_hash, /^scrypt\$/); assert.equal(user!.password_hash.includes(password), false);
  await new Promise<void>(resolve => { server.close(() => resolve()); server.closeAllConnections(); }); await database.close();
  const bytes = await readFile(path);
  for (const secret of [password, registered.token, fromRouter.token]) assert.equal(bytes.includes(Buffer.from(secret)), false);
  database = new SqliteConnection(path); identity = new IdentityService(database); await identity.ready();
  server = createAccountServer(identity); server.listen(address.port, "127.0.0.1"); await once(server, "listening");
  assert.deepEqual(await desktop.current(registered.token), registered.principal);
  await router.revoke(`Bearer ${registered.token}`);
  await assert.rejects(desktop.current(registered.token), error => error instanceof IdentityError && error.status === 401);
  assert.deepEqual(await desktop.current(fromRouter.token), fromRouter.principal, "one logout does not revoke another independently issued session");
});
